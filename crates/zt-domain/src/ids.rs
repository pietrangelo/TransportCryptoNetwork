use core::fmt;
use core::num::NonZeroU32;

use crate::error::DomainError;
use crate::limits::MAX_NODE_ID_LEN;

/// Logical name of a target node, used as an alias in the Ansible inventory.
///
/// Invariants (restricted DNS label, RFC 1035 §2.3.4, lowercase only):
/// - length `1..=63`;
/// - alphabet `[a-z0-9-]`, hence printable ASCII only and no control bytes;
/// - does not start or end with `-`.
///
/// The restricted alphabet eliminates at the root Unicode homograph attacks, log injection
/// and comparison ambiguity (no case folding).
#[derive(Clone, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct NodeId(Box<str>);

impl NodeId {
    /// The name as a string.
    #[must_use]
    pub fn as_str(&self) -> &str {
        &self.0
    }

    /// The name as bytes (the form used on the wire).
    #[must_use]
    pub fn as_bytes(&self) -> &[u8] {
        self.0.as_bytes()
    }

    /// Length in bytes (always in `1..=63`).
    #[must_use]
    pub fn len(&self) -> usize {
        self.0.len()
    }

    /// Always `false`: an empty `NodeId` cannot be constructed. Present for consistency with `len`.
    #[must_use]
    pub fn is_empty(&self) -> bool {
        false
    }
}

impl TryFrom<&[u8]> for NodeId {
    type Error = DomainError;

    fn try_from(bytes: &[u8]) -> Result<Self, Self::Error> {
        let len = bytes.len();
        if len == 0 {
            return Err(DomainError::NodeIdEmpty);
        }
        if len > MAX_NODE_ID_LEN {
            return Err(DomainError::NodeIdTooLong {
                len,
                max: MAX_NODE_ID_LEN,
            });
        }
        if let Some(position) = bytes
            .iter()
            .position(|b| !matches!(b, b'a'..=b'z' | b'0'..=b'9' | b'-'))
        {
            return Err(DomainError::NodeIdInvalidByte { position });
        }
        if bytes.first() == Some(&b'-') || bytes.last() == Some(&b'-') {
            return Err(DomainError::NodeIdHyphenAtEdge);
        }
        // All bytes are ASCII: the conversion cannot fail, but we handle it without panicking.
        let text = core::str::from_utf8(bytes).map_err(|e| DomainError::NodeIdInvalidByte {
            position: e.valid_up_to(),
        })?;
        Ok(Self(text.into()))
    }
}

impl TryFrom<&str> for NodeId {
    type Error = DomainError;

    fn try_from(text: &str) -> Result<Self, Self::Error> {
        Self::try_from(text.as_bytes())
    }
}

impl fmt::Display for NodeId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.0)
    }
}

impl fmt::Debug for NodeId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "NodeId({})", self.0)
    }
}

/// Identifier of a client↔agent end-to-end session.
///
/// 128 bits generated by a CSPRNG in the adapter (the domain does not generate randomness).
/// The all-zero value is reserved and rejected.
#[derive(Clone, Copy, PartialEq, Eq, Hash)]
pub struct SessionId([u8; Self::LEN]);

impl SessionId {
    /// Length in bytes.
    pub const LEN: usize = 16;

    /// Builds a `SessionId` from 16 random bytes.
    ///
    /// # Errors
    /// [`DomainError::SessionIdZero`] if all bytes are zero.
    pub fn from_bytes(bytes: [u8; Self::LEN]) -> Result<Self, DomainError> {
        if bytes.iter().all(|&b| b == 0) {
            return Err(DomainError::SessionIdZero);
        }
        Ok(Self(bytes))
    }

    /// The identifier bytes.
    #[must_use]
    pub const fn as_bytes(&self) -> &[u8; Self::LEN] {
        &self.0
    }
}

impl TryFrom<&[u8]> for SessionId {
    type Error = DomainError;

    fn try_from(bytes: &[u8]) -> Result<Self, Self::Error> {
        let array: [u8; Self::LEN] = bytes.try_into().map_err(|_| DomainError::InvalidLength {
            what: "session id",
            expected: Self::LEN,
            actual: bytes.len(),
        })?;
        Self::from_bytes(array)
    }
}

impl fmt::Debug for SessionId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str("SessionId(")?;
        for b in &self.0 {
            write!(f, "{b:02x}")?;
        }
        f.write_str(")")
    }
}

/// Identifier of a stream multiplexed over a connection.
///
/// Stream `0` is reserved for connection control frames, so a `StreamId`
/// is always non-zero (guaranteed by the [`NonZeroU32`] type).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct StreamId(NonZeroU32);

impl StreamId {
    /// The numeric value (always `> 0`).
    #[must_use]
    pub const fn get(self) -> u32 {
        self.0.get()
    }
}

impl TryFrom<u32> for StreamId {
    type Error = DomainError;

    fn try_from(raw: u32) -> Result<Self, Self::Error> {
        NonZeroU32::new(raw)
            .map(Self)
            .ok_or(DomainError::StreamIdZero)
    }
}

impl fmt::Display for StreamId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}", self.0)
    }
}

#[cfg(test)]
#[allow(
    clippy::unwrap_used,
    clippy::expect_used,
    clippy::indexing_slicing,
    clippy::arithmetic_side_effects,
    clippy::doc_markdown
)]
mod tests {
    use super::*;

    #[test]
    fn node_id_accepts_dns_labels() {
        for ok in ["a", "web-01", "db0", "x".repeat(63).as_str()] {
            assert!(NodeId::try_from(ok).is_ok(), "{ok} should be valid");
        }
    }

    #[test]
    fn node_id_rejects_empty() {
        assert_eq!(NodeId::try_from(""), Err(DomainError::NodeIdEmpty));
    }

    #[test]
    fn node_id_rejects_too_long() {
        let long = "a".repeat(64);
        assert_eq!(
            NodeId::try_from(long.as_str()),
            Err(DomainError::NodeIdTooLong { len: 64, max: 63 })
        );
    }

    #[test]
    fn node_id_rejects_forbidden_bytes() {
        let cases: [(&[u8], usize); 7] = [
            (b"Web", 0),        // uppercase: no ambiguous case folding
            (b"web.01", 3),     // no FQDN: a single label
            (b"web 01", 3),     // spaces
            (b"web\n01", 3),    // log injection
            (b"web\x0001", 3),  // NUL byte
            (b"w\xc3\xa9b", 1), // non-ASCII UTF-8 (homographs)
            (b"../etc", 0),     // path traversal if used in a path
        ];
        for (input, position) in cases {
            assert_eq!(
                NodeId::try_from(input),
                Err(DomainError::NodeIdInvalidByte { position }),
                "input {input:?}"
            );
        }
    }

    #[test]
    fn node_id_rejects_hyphen_at_edges() {
        for bad in ["-web", "web-", "-"] {
            assert_eq!(NodeId::try_from(bad), Err(DomainError::NodeIdHyphenAtEdge));
        }
    }

    #[test]
    fn session_id_rejects_all_zeros_and_wrong_length() {
        assert_eq!(
            SessionId::from_bytes([0; 16]),
            Err(DomainError::SessionIdZero)
        );
        assert_eq!(
            SessionId::try_from(&[1_u8; 15][..]),
            Err(DomainError::InvalidLength {
                what: "session id",
                expected: 16,
                actual: 15
            })
        );
        assert!(SessionId::try_from(&[7_u8; 16][..]).is_ok());
    }

    #[test]
    fn stream_id_zero_is_reserved() {
        assert_eq!(StreamId::try_from(0), Err(DomainError::StreamIdZero));
        assert_eq!(StreamId::try_from(42).map(StreamId::get), Ok(42));
    }
}
